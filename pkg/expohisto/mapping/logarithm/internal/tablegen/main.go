package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"math/big"
	"os"
)

const significandWidth = 52

func main() {
	scale := flag.Int("scale", 8, "maximum table scale")
	output := flag.String("output", "tables_generated.go", "generated Go file")
	flag.Parse()

	if *scale < 1 || *scale > 15 {
		fmt.Fprintln(os.Stderr, "scale must be between 1 and 15")
		os.Exit(2)
	}

	boundaries := generateBoundaries(*scale)
	indexTable, shift := generateIndexTable(*scale, boundaries)
	source, err := render(*scale, shift, boundaries, indexTable)
	if err != nil {
		fmt.Fprintf(os.Stderr, "format generated table: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*output, source, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write generated table: %v\n", err)
		os.Exit(1)
	}
}

func generateBoundaries(scale int) []uint64 {
	n := 1 << scale
	boundaries := make([]uint64, 0, n+3)
	boundaries = append(boundaries, 0, 1)

	for k := 1; k < n; k++ {
		x := new(big.Int).Lsh(big.NewInt(1), uint(significandWidth*n+k))
		for range scale {
			x = ceilSqrt(x)
		}
		boundaries = append(boundaries, x.Uint64()&((1<<significandWidth)-1))
	}
	return append(boundaries, 1<<significandWidth, 1<<significandWidth)
}

func ceilSqrt(value *big.Int) *big.Int {
	root := new(big.Int).Sqrt(value)
	squared := new(big.Int).Mul(new(big.Int).Set(root), root)
	if squared.Cmp(value) != 0 {
		root.Add(root, big.NewInt(1))
	}
	return root
}

func generateIndexTable(scale int, boundaries []uint64) ([]uint16, int) {
	n := 1 << scale
	shift := 51 - scale
	table := make([]uint16, 2*n)
	j := 0
	for i := range table {
		lowerBound := uint64(i) << shift
		for lowerBound >= boundaries[j+1] {
			j++
		}
		table[i] = uint16(j)
	}
	return table, shift
}

func render(scale, shift int, boundaries []uint64, indexTable []uint16) ([]byte, error) {
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Copyright The OpenTelemetry Authors")
	fmt.Fprintln(&output, "// SPDX-License-Identifier: Apache-2.0")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "package logarithm")
	fmt.Fprintln(&output)
	fmt.Fprintf(&output, "const tableScale int32 = %d\n", scale)
	fmt.Fprintf(&output, "const tableShift = %d\n\n", shift)
	fmt.Fprintf(&output, "var boundaries = [...]uint64{\n")
	for i, value := range boundaries {
		if i%4 == 0 {
			fmt.Fprint(&output, "\t")
		}
		fmt.Fprintf(&output, "0x%013x, ", value)
		if i%4 == 3 || i == len(boundaries)-1 {
			fmt.Fprintln(&output)
		}
	}
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "var indexTable = [...]uint16{")
	for i, value := range indexTable {
		if i%16 == 0 {
			fmt.Fprint(&output, "\t")
		}
		fmt.Fprintf(&output, "%d, ", value)
		if i%16 == 15 || i == len(indexTable)-1 {
			fmt.Fprintln(&output)
		}
	}
	fmt.Fprintln(&output, "}")
	return format.Source(output.Bytes())
}
